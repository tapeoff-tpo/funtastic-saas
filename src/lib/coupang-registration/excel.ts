import ExcelJS from 'exceljs'
import JSZip from 'jszip'
import { createHash, randomUUID } from 'node:crypto'
import { createRegistrationRow, imageStem, isAutomaticTemplateColumn, LABEL_FIELD, money, registrationFieldKey, registrationFieldValue, rowFields, rowIssues, type RegistrationDraft, type RegistrationRow, type SavedFile, type TemplateInfo } from './model'
import { loadRegistrationWorkbook } from './xlsx-compat'

function cellText(cell: ExcelJS.Cell): string {
  const value = cell.value
  if (value === null || value === undefined) return ''
  if (typeof value === 'object') {
    if ('formula' in value || 'sharedFormula' in value) return String(value.result ?? '')
    if ('richText' in value) return value.richText.map((part) => part.text).join('')
    if ('text' in value) return value.text
  }
  return String(value)
}

const MAX_TEMPLATE_CHOICES = 500
const MAX_TEMPLATE_CHOICE_LENGTH = 2000

function columnNumber(letters: string) {
  return [...letters].reduce((number, letter) => number * 26 + letter.charCodeAt(0) - 64, 0)
}

/** Read literal options only; never evaluate formulas or fetch external workbooks. */
function choicesFromRange(workbook: ExcelJS.Workbook, reference: string): string[] | undefined {
  const match = /^(?:'((?:[^']|'')+)'|([^'!\[\]]+))!\$?([A-Z]{1,3})\$?([1-9]\d{0,6})(?::\$?([A-Z]{1,3})\$?([1-9]\d{0,6}))?$/.exec(reference)
  if (!match) return
  const sheetName = (match[1]?.replaceAll("''", "'") ?? match[2])
  if (/[\[\]]/.test(sheetName)) return
  const sheet = workbook.getWorksheet(sheetName)
  if (!sheet) return
  const startColumn = columnNumber(match[3])
  const endColumn = columnNumber(match[5] ?? match[3])
  const startRow = Number(match[4])
  const endRow = Number(match[6] ?? match[4])
  if (endColumn < startColumn || endRow < startRow || endColumn > 16384 || endRow > 1048576
    || (endColumn - startColumn + 1) * (endRow - startRow + 1) > MAX_TEMPLATE_CHOICES) return
  const choices: string[] = []
  for (let row = startRow; row <= endRow; row++) {
    for (let column = startColumn; column <= endColumn; column++) {
      const value = sheet.getCell(row, column).value
      if (value === null || value === undefined) continue
      if (!['string', 'number', 'boolean'].includes(typeof value)) return
      const text = String(value)
      if (text.length > MAX_TEMPLATE_CHOICE_LENGTH) return
      if (text.trim()) choices.push(text)
    }
  }
  return choices
}

function templateChoices(workbook: ExcelJS.Workbook, cell: ExcelJS.Cell): { choices?: string[]; allowCustom?: boolean } {
  const validation = cell.dataValidation
  if (validation?.type !== 'list' || validation.formulae?.length !== 1 || typeof validation.formulae[0] !== 'string') return {}
  const formula = validation.formulae[0].replace(/^=/, '')
  if (!formula || formula.length > MAX_TEMPLATE_CHOICES * (MAX_TEMPLATE_CHOICE_LENGTH + 1) + 2) return {}
  let choices: string[] | undefined
  if (formula.startsWith('"') && formula.endsWith('"')) {
    const contents = formula.slice(1, -1)
    if (contents.replaceAll('""', '').includes('"')) return {}
    choices = contents.replaceAll('""', '"').split(',')
  } else if (formula.includes('!')) {
    choices = choicesFromRange(workbook, formula)
  } else if (/^[A-Za-z_][A-Za-z\d_.]{0,254}$/.test(formula)) {
    const names = workbook.definedNames.model.filter((item) => item.name === formula)
    if (names.length !== 1 || names[0].ranges.length !== 1) return {}
    choices = choicesFromRange(workbook, names[0].ranges[0])
  }
  if (!choices?.length || choices.length > MAX_TEMPLATE_CHOICES || choices.some((choice) => choice.length > MAX_TEMPLATE_CHOICE_LENGTH)) return {}
  choices = [...new Set(choices.filter((choice) => choice.trim()))]
  const allowCustom = validation.showErrorMessage !== true || ['warning', 'information'].includes(validation.errorStyle ?? '')
  return choices.length ? { choices, allowCustom } : {}
}

function templateInfo(workbook: ExcelJS.Workbook, id: string, name: string): TemplateInfo {
  const sheets = workbook.worksheets.filter((sheet) => sheet.name.startsWith('QF_')).map((sheet) => {
    const columns: TemplateInfo['sheets'][number]['columns'] = []
    sheet.getRow(5).eachCell((cell, column) => {
      const label = cellText(cell).trim()
      if (label) {
        const guide = cellText(sheet.getCell(7, column)).slice(0, 10000)
        const example = cellText(sheet.getCell(8, column))
        let hasFormula = false
        sheet.getColumn(column).eachCell((entry) => { if (Number(entry.row) >= 9 && entry.type === ExcelJS.ValueType.Formula) hasFormula = true })
        // Price/image columns are populated from their dedicated screen controls, even
        // when an older quote happens to contain a sample calculation in those cells.
        const controlled = ['상품명', '공급가', '쿠팡 판매가', '대표이미지 파일명', '추가이미지 파일명', '상세이미지 파일명', 'HTML 상품 상세 컨텐츠', LABEL_FIELD].includes(label)
        const autoGenerated = label.replace(/\s/g, '') === '고시명' || !controlled && hasFormula && /수식[^\n]*입력하지|자동\s*(?:설정|생성|계산)/.test(`${guide}\n${example}`)
        columns.push({ column, label, requirement: cellText(sheet.getCell(6, column)).trim(), guide, ...templateChoices(workbook, sheet.getCell(9, column)), ...(autoGenerated ? { autoGenerated: true } : {}) })
      }
    })
    if (!columns.some((column) => column.label === '상품명') || !columns.some((column) => column.label === '공급가')) throw new Error(`${sheet.name}: 지원하는 쿠팡 카테고리 견적서가 아닙니다.`)
    return { name: sheet.name, columns }
  })
  if (!sheets.length || sheets.length > 20) throw new Error('쿠팡에서 받은 카테고리 견적서(QF 시트)를 선택해주세요.')
  return { id, name, sheets }
}

export async function readTemplate(buffer: Buffer, name: string) {
  if (buffer.length > 3_000_000) throw new Error('견적서는 파일당 3MB까지 불러올 수 있습니다.')
  const id = createHash('sha256').update(buffer).digest('hex')
  const workbook = await loadRegistrationWorkbook(buffer)
  const info = templateInfo(workbook, id, name)
  const rows: RegistrationRow[] = []
  for (const definition of info.sheets) {
    const sheet = workbook.getWorksheet(definition.name)!
    if (sheet.rowCount > 5000 || sheet.columnCount > 200) throw new Error('견적서가 지원하는 행·열 범위를 초과했습니다.')
    const nameColumn = definition.columns.find((column) => column.label === '상품명')!.column
    for (let index = 9; index <= sheet.rowCount; index++) {
      const productName = cellText(sheet.getCell(index, nameColumn)).trim()
      if (!productName) continue
      const fields = Object.fromEntries(definition.columns.map((column) => [registrationFieldKey({ templateId: id }, definition, column), cellText(sheet.getCell(index, column.column))]))
      rows.push({
        ...createRegistrationRow(), id: randomUUID(), templateId: id, sheetName: definition.name, name: productName,
        priceMode: 'manual', manualSupplyPrice: money(fields['공급가']),
        saleMode: money(fields['쿠팡 판매가']) === null ? 'auto' : 'manual', manualSalePrice: money(fields['쿠팡 판매가']), fields,
        primaryImage: fields['대표이미지 파일명'] ?? '', label: fields[LABEL_FIELD] ?? '',
      })
    }
  }
  if (rows.length > 500) throw new Error('한 작업에는 최대 500개 등록행을 사용할 수 있습니다.')
  return { template: { ...info, file: { name, data: buffer.toString('base64') } }, rows }
}

const numericFields = new Set(['공급가', '쿠팡 판매가', '박스 내 SKU 수량', '한 개 단품 포장 무게', '유통기간 *식품의 경우 소비기간\n(일수기재)'])

export async function buildRegistrationArchive(draft: RegistrationDraft, rowIds?: readonly string[]): Promise<Buffer> {
  if (rowIds !== undefined) {
    const selected = new Set(rowIds)
    if (!selected.size) throw new Error('엑셀로 출력할 상품을 선택해주세요.')
    const rows = draft.rows.filter((row) => selected.has(row.id))
    if (rows.length !== selected.size) throw new Error('선택한 상품을 현재 작업에서 찾을 수 없습니다.')
    draft = { ...draft, rows }
  }
  if (!draft.rows.length) throw new Error('등록할 상품을 추가해주세요.')
  const zip = new JSZip()
  const usedTemplates = draft.templates.filter((template) => draft.rows.some((row) => row.templateId === template.id))
  if (!usedTemplates.length) throw new Error('쿠팡 견적서를 먼저 불러와주세요.')
  // Re-read the actual uploaded template rather than trusting client-supplied columns.
  const verified: RegistrationDraft = { ...draft, templates: [] }
  const workbooks = new Map<string, ExcelJS.Workbook>()
  for (const template of usedTemplates) {
    const buffer = Buffer.from(template.file.data, 'base64')
    if (createHash('sha256').update(buffer).digest('hex') !== template.id) throw new Error('견적서 파일이 변경되었습니다. 다시 불러와주세요.')
    const workbook = await loadRegistrationWorkbook(buffer)
    verified.templates.push({ ...templateInfo(workbook, template.id, template.name), file: template.file })
    workbooks.set(template.id, workbook)
  }
  for (const row of draft.rows) {
    const issues = rowIssues(row, verified)
    if (issues.length) throw new Error(`${row.name}: ${issues.slice(0, 3).join(', ')}`)
  }
  for (const template of verified.templates) {
    const workbook = workbooks.get(template.id)!
    for (const definition of template.sheets) {
      const sheet = workbook.getWorksheet(definition.name)!
      if (sheet.rowCount > 5000 || sheet.columnCount > 200) throw new Error('지원하는 견적서 크기를 초과했습니다.')
      const formulaSources = new Map<number, { address: string; formula: string }>()
      const translationSheet = new ExcelJS.Workbook().addWorksheet('translation')
      for (const column of definition.columns.filter(isAutomaticTemplateColumn)) {
        sheet.getColumn(column.column).eachCell((cell) => {
          if (Number(cell.row) < 9 || formulaSources.has(column.column) || cell.type !== ExcelJS.ValueType.Formula) return
          formulaSources.set(column.column, { address: cell.address, formula: cell.formula })
          translationSheet.getCell(cell.address).value = { formula: cell.formula }
        })
      }
      for (let index = 9; index <= sheet.rowCount; index++) {
        for (const column of definition.columns) {
          if (isAutomaticTemplateColumn(column)) continue
          const cell = sheet.getCell(index, column.column)
          // Keep template formulas, validations, styles, hidden metadata and version rows.
          if (cell.type !== ExcelJS.ValueType.Formula) cell.value = null
        }
      }
      const entries = draft.rows.filter((row) => row.templateId === template.id && row.sheetName === definition.name)
      for (const [index, entry] of entries.entries()) {
        const fields = rowFields(entry, draft.rounding, draft.labels)
        for (const column of definition.columns) {
          const value = registrationFieldValue({ ...entry, fields }, definition, column) ?? ''
          const cell = sheet.getCell(index + 9, column.column)
          if (isAutomaticTemplateColumn(column)) {
            // Never replace a category-derived formula with an imported cached value.
            // Extend its relative references when more products than template rows are exported.
            const source = formulaSources.get(column.column)
            if (cell.value === null && source && cell.address !== source.address) {
              translationSheet.getCell(cell.address).value = { sharedFormula: source.address }
              cell.value = { formula: translationSheet.getCell(cell.address).formula }
              workbook.calcProperties.fullCalcOnLoad = true
            }
            continue
          }
          if (!value && cell.type === ExcelJS.ValueType.Formula) continue
          if (value.length > 32767) throw new Error(`${entry.name}: ${column.label} 내용이 너무 깁니다.`)
          // Strings are literal cell values, never evaluate imported HTML or '=' text as formulas.
          cell.value = value === '' ? null : numericFields.has(column.label) && money(value) !== null ? money(value)! : value
        }
      }
    }
    const safeName = template.name.normalize('NFC').replace(/[\\/]/g, '_').replace(/\.xlsx$/i, '')
    zip.file(`견적서/${safeName}_등록용.xlsx`, await workbook.xlsx.writeBuffer())
  }
  const neededLabels = new Set(draft.rows.flatMap((row) => row.label.split(',').map(imageStem)))
  for (const file of draft.labels) {
    if (neededLabels.has(imageStem(file.name))) zip.file(`품질표시/${file.name.normalize('NFC')}`, checkedLabel(file))
  }
  zip.file('사용방법.txt', '견적서 폴더의 엑셀 파일을 쿠팡 서플라이어 허브에 업로드하세요.\n이미지는 공개 URL과 HTML로 연결되어 있습니다. 품질표시 폴더가 있으면 해당 이미지도 첨부하세요.\n내부 필수항목 검사를 통과한 파일이며 쿠팡 자체 검증·등록 승인은 별도로 진행해야 합니다.\n')
  return zip.generateAsync({ type: 'nodebuffer', compression: 'DEFLATE' })
}

export function checkedLabel(file: SavedFile): Buffer {
  const buffer = Buffer.from(file.data, 'base64')
  const jpeg = buffer[0] === 0xff && buffer[1] === 0xd8 && buffer[2] === 0xff
  const png = buffer.subarray(0, 8).equals(Buffer.from([137, 80, 78, 71, 13, 10, 26, 10]))
  if ((!jpeg && !png) || !/\.(jpe?g|png)$/i.test(file.name)) throw new Error('품질표시 파일은 JPG·PNG 이미지만 사용할 수 있습니다.')
  return buffer
}
