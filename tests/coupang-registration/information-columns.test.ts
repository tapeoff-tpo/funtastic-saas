import { describe, expect, it } from 'vitest'
import { buildInformationColumns, groupInformationRows } from '@/app/(auth)/operations/coupang-registration/information-columns'
import { createRegistrationRow, LABEL_FIELD, registrationCommonSheet, registrationFieldKey, type RegistrationDraft, type RegistrationRow, type TemplateColumn, type TemplateSheet } from '@/lib/coupang-registration/model'

const column = (position: number, label: string, requirement = '필수', extra: Partial<TemplateColumn> = {}): TemplateColumn => ({ column: position, label, requirement, guide: `${label} 안내`, ...extra })
const template = (id: string, sheet: TemplateSheet): RegistrationDraft['templates'][number] => ({ id, name: `${id}.xlsx`, file: { name: `${id}.xlsx`, data: '' }, sheets: [sheet] })
const row = (id: string, templateId: string, sheetName: string, fields: Record<string, string> = {}): RegistrationRow => ({ ...createRegistrationRow(), id, templateId, sheetName, fields })
const key = (label: string, occurrence = 1) => JSON.stringify([label, occurrence])

describe('horizontal registration information columns', () => {
  it('unions labels across templates while preserving independent duplicate columns and source options', () => {
    const firstSheet: TemplateSheet = { name: 'QF_1_선반', columns: [
      column(7, '색상', '필수', { choices: ['검정', '흰색'] }),
      column(15, '설치지원방식', '선택', { choices: ['완전 조립', '조립 필요'] }),
      column(53, '설치지원방식', '조건부 필수', { choices: ['고객직접설치', '방문설치'] }),
      column(62, '색상'),
    ] }
    const secondSheet: TemplateSheet = { name: 'QF_2_행거', columns: [
      column(6, '색상', '선택', { choices: ['브라운'] }), column(20, '소재'),
      column(47, '설치지원방식'), column(56, '색상', '조건부 필수'),
    ] }
    const firstBase = row('first', 'first-file', firstSheet.name)
    const first = { ...firstBase, fields: Object.fromEntries(firstSheet.columns.map((source, index) => [registrationFieldKey(firstBase, firstSheet, source), ['검정', '완전 조립', '고객직접설치', '먹색'][index]])) }
    const secondBase = row('second', 'second-file', secondSheet.name)
    const second = { ...secondBase, fields: { 소재: '철제', [registrationFieldKey(secondBase, secondSheet, secondSheet.columns[0])]: '브라운' } }
    const result = buildInformationColumns([first, second], [template(first.templateId, firstSheet), template(second.templateId, secondSheet)])

    expect(result.columns.map(item => item.headerLabel)).toEqual(['색상', '설치지원방식', '설치지원방식 2', '색상 2', '소재'])
    expect(result.columns.find(item => item.key === key('색상', 2))).toMatchObject({ occurrence: 2, requiredAny: true, conditionalAny: true })
    expect(result.rows.get(first.id)?.columns.get(key('설치지원방식'))).toEqual({ column: firstSheet.columns[1], fieldKey: registrationFieldKey(first, firstSheet, firstSheet.columns[1]), value: '완전 조립' })
    expect(result.rows.get(first.id)?.columns.get(key('설치지원방식', 2))?.value).toBe('고객직접설치')
    expect(result.rows.get(second.id)?.columns.get(key('색상'))?.column.choices).toEqual(['브라운'])
    expect(result.rows.get(second.id)?.columns.get(key('설치지원방식', 2))).toBeUndefined()
  })

  it('shows empty optional headers and counts duplicates before excluding automatic columns', () => {
    const sheet: TemplateSheet = { name: 'QF_3_중복', columns: [
      column(7, '색상', '선택'), column(62, '색상'),
      column(70, '동일 자동항목', '필수', { autoGenerated: true }), column(71, '동일 자동항목'),
    ] }
    const value = row('row', 'file', sheet.name)
    const result = buildInformationColumns([value], [template(value.templateId, sheet)])
    expect(result.columns.map(item => item.headerLabel)).toEqual(['색상', '색상 2', '동일 자동항목 2'])
    expect(result.rows.get(value.id)?.columns.get(key('색상'))?.value).toBe('')
    expect(result.rows.get(value.id)?.columns.get(key('색상', 2))?.fieldKey).toBe(registrationFieldKey(value, sheet, sheet.columns[1]))
  })

  it('keeps every blank optional header in its original position without adding absent columns to another row', () => {
    const firstSheet: TemplateSheet = { name: 'QF_1_가구', columns: [column(1, '재질', '선택'), column(2, '빈 선택항목', '선택')] }
    const secondSheet: TemplateSheet = { name: 'QF_2_가방', columns: [column(10, '재질', '선택'), column(11, '전용항목')] }
    const first = row('first', 'first-file', firstSheet.name)
    const second = row('second', 'second-file', secondSheet.name, { 재질: '면' })
    const result = buildInformationColumns([first, second], [template(first.templateId, firstSheet), template(second.templateId, secondSheet)])
    expect(result.columns.map(item => item.label)).toEqual(['재질', '빈 선택항목', '전용항목'])
    expect(result.rows.get(first.id)?.columns.get(key('재질'))?.value).toBe('')
    expect(result.rows.get(first.id)?.columns.has(key('전용항목'))).toBe(false)
    expect(result.rows.get(first.id)?.columns.get(key('빈 선택항목'))).toMatchObject({ column: firstSheet.columns[1], value: '' })
    expect(result.columns[0]).toMatchObject({ requiredAny: false, conditionalAny: false })
  })

  it('omits dedicated controls and formula columns even when required or populated', () => {
    const labels = ['상품명', '공급가', '쿠팡 판매가', '대표이미지 파일명', '추가이미지 파일명', '상세이미지 파일명', 'HTML 상품 상세 컨텐츠', LABEL_FIELD, '고시명', '고 시 명', '자동 계산', '편집항목']
    const sheet: TemplateSheet = { name: 'QF_1_자동', columns: labels.map((label, index) => column(index + 1, label, '필수', label === '자동 계산' ? { autoGenerated: true } : {})) }
    const value = row('row', 'file', sheet.name, Object.fromEntries(labels.map(label => [label, '저장값'])))
    const result = buildInformationColumns([value], [template(value.templateId, sheet)])
    expect(result.columns.map(item => item.label)).toEqual(['편집항목'])
    expect([...result.rows.get(value.id)!.columns.keys()]).toEqual([key('편집항목')])
  })

  it('shows all common fields without claiming official requirements when no selected sheet exists', () => {
    const value = row('row', 'missing-file', 'missing-sheet', { 브랜드: '사용자 브랜드' })
    const result = buildInformationColumns([value], [])
    expect(result.columns.map(item => item.label)).toEqual(registrationCommonSheet.columns.map(item => item.label))
    expect(result.columns.every(item => !item.requiredAny && !item.conditionalAny)).toBe(true)
    expect(result.rows.get(value.id)).toMatchObject({ sheet: registrationCommonSheet, hasOfficialSheet: false })
    expect(result.rows.get(value.id)?.columns.get(key('브랜드'))?.value).toBe('사용자 브랜드')
    expect(result.rows.get(value.id)?.columns.get(key('구성품'))?.value).toBe('')
  })

  it('preserves legacy fallback, explicit scoped clears and the untouched input data', () => {
    const sheet: TemplateSheet = { name: 'QF_1_중복', columns: [column(7, '색상'), column(62, '색상')] }
    const base = row('row', 'file', sheet.name, { 색상: '검정' })
    const value = { ...base, fields: { ...base.fields, [registrationFieldKey(base, sheet, sheet.columns[0])]: '' } }
    const templates = [template(value.templateId, sheet)]
    const before = JSON.stringify({ value, templates })
    Object.freeze(value.fields)
    Object.freeze(value)
    sheet.columns.forEach(Object.freeze)
    Object.freeze(sheet.columns)
    Object.freeze(sheet)
    const result = buildInformationColumns([value], templates)
    expect(result.rows.get(value.id)?.columns.get(key('색상'))?.value).toBe('')
    expect(result.rows.get(value.id)?.columns.get(key('색상', 2))?.value).toBe('검정')
    expect(JSON.stringify({ value, templates })).toBe(before)
  })

  it('returns no columns or row mappings for an empty list', () => {
    expect(buildInformationColumns([], [])).toEqual({ columns: [], rows: new Map() })
  })
})

describe('registration information sheet groups', () => {
  it('groups by both file and sheet and keeps the first appearance and within-group row order', () => {
    const firstSheet: TemplateSheet = { name: 'QF_1_가구_선반', columns: [column(1, '소재')] }
    const otherSheet: TemplateSheet = { name: 'QF_2_가구_행거', columns: [column(1, '설치방식')] }
    const firstFile = { ...template('file-a', firstSheet), sheets: [firstSheet, otherSheet] }
    const secondFile = template('file-b', firstSheet)
    const rows = [row('first', firstFile.id, firstSheet.name), row('second', firstFile.id, otherSheet.name), row('third', secondFile.id, firstSheet.name), row('fourth', firstFile.id, firstSheet.name)]
    const groups = groupInformationRows(rows, [firstFile, secondFile])
    expect(groups.map(group => ({ key: group.key, name: group.name, fileName: group.fileName, ids: group.rows.map(row => row.id), official: group.hasOfficialSheet }))).toEqual([
      { key: JSON.stringify([firstFile.id, firstSheet.name]), name: '가구_선반', fileName: firstFile.name, ids: ['first', 'fourth'], official: true },
      { key: JSON.stringify([firstFile.id, otherSheet.name]), name: '가구_행거', fileName: firstFile.name, ids: ['second'], official: true },
      { key: JSON.stringify([secondFile.id, firstSheet.name]), name: '가구_선반', fileName: secondFile.name, ids: ['third'], official: true },
    ])
    expect(groups[0].rows[0]).toBe(rows[0])
    expect(groups[0].rows[1]).toBe(rows[3])
  })

  it('keeps missing files, missing sheet assignments and invalid sheet references in one common group', () => {
    const sheet: TemplateSheet = { name: 'QF_1_선반', columns: [column(1, '소재')] }
    const file = template('file', sheet)
    const missing = [row('empty', '', ''), row('missing-file', 'not-found', sheet.name), row('missing-sheet', file.id, 'not-found')]
    const official = row('official', file.id, sheet.name)
    const groups = groupInformationRows([missing[0], official, ...missing.slice(1)], [file])
    expect(groups).toHaveLength(2)
    expect(groups[0]).toMatchObject({ name: '양식 미선택', fileName: '', hasOfficialSheet: false, rows: missing })
    expect(groups[1]).toMatchObject({ name: '선반', fileName: file.name, hasOfficialSheet: true, rows: [official] })
    expect(buildInformationColumns(groups[0].rows, [file]).columns.map(column => column.label)).toEqual(registrationCommonSheet.columns.map(column => column.label))
  })

  it('builds each group from only its original headers, including blank optional fields and independent duplicates', () => {
    const shelf: TemplateSheet = { name: 'QF_2379_선반', columns: [column(7, '색상'), column(15, '설치지원방식', '선택'), column(53, '설치지원방식', '조건부 필수'), column(62, '색상'), column(70, '선반 선택정보', '선택')] }
    const bag: TemplateSheet = { name: 'QF_1_가방', columns: [column(2, '가방종류'), column(3, '가방 선택정보', '선택')] }
    const templates = [template('shelf-file', shelf), template('bag-file', bag)]
    const shelfRow = row('shelf', templates[0].id, shelf.name, { 색상: '검정' })
    const bagRow = row('bag', templates[1].id, bag.name)
    const groups = groupInformationRows([shelfRow, bagRow], templates)
    const shelfColumns = buildInformationColumns(groups[0].rows, templates)
    const bagColumns = buildInformationColumns(groups[1].rows, templates)
    expect(shelfColumns.columns.map(column => column.headerLabel)).toEqual(['색상', '설치지원방식', '설치지원방식 2', '색상 2', '선반 선택정보'])
    expect(bagColumns.columns.map(column => column.headerLabel)).toEqual(['가방종류', '가방 선택정보'])
    expect(shelfColumns.rows.get(shelfRow.id)?.columns.get(key('색상', 2))?.fieldKey).toBe(registrationFieldKey(shelfRow, shelf, shelf.columns[3]))
    expect(shelfColumns.rows.get(shelfRow.id)?.columns.has(key('가방종류'))).toBe(false)
    expect(bagColumns.rows.get(bagRow.id)?.columns.has(key('선반 선택정보'))).toBe(false)
  })

  it('keeps saved information untouched when grouping frozen row inputs and accepts an empty list', () => {
    const sheet: TemplateSheet = { name: 'QF_1_선반', columns: [column(1, '소재')] }
    const file = template('file', sheet)
    const value = { ...row('saved', file.id, sheet.name, { 소재: '수동 입력' }), name: '보존할 이름', label: '기존 라벨.jpg', manualSupplyPrice: 17700, manualSalePrice: 29500 }
    const original = JSON.stringify(value)
    Object.freeze(value.fields)
    Object.freeze(value)
    const groups = groupInformationRows(Object.freeze([value]), [file])
    expect(groups[0].rows[0]).toBe(value)
    expect(JSON.stringify(groups[0].rows[0])).toBe(original)
    expect(groupInformationRows([], [file])).toEqual([])
  })
})
