import { describe, expect, it } from 'vitest'
import { applyProductMasterDefaults, applyRegistrationDefaults, createRegistrationRow, registrationFieldKey, registrationFieldValue, type RegistrationProductMaster, type RegistrationRow, type TemplateColumn, type TemplateSheet } from '@/lib/coupang-registration/model'

const master: RegistrationProductMaster = {
  itemId: 'known-item', match: 'sku', noticeSize: '25*12*41cm', noticeWeight: '400g',
  noticeMaterial: '캔버스', noticeManufacturer: '확인된 제조공장', noticeCountry: '중국',
}
const column = (column: number, label: string, choices?: string[]): TemplateColumn => ({ column, label, requirement: '필수', guide: '', ...(choices ? { choices } : {}) })
const sheet = (...labels: string[]): TemplateSheet => ({ name: 'QF_2_상품정보', columns: labels.map((label, index) => column(index + 1, label)) })
const row = (patch: Partial<RegistrationRow> = {}): RegistrationRow => ({ ...createRegistrationRow(), stage: 'information', templateId: 'original-file', optionName: '베이지', ...patch })

describe('approved editable category defaults', () => {
  it('uses the original dropdown spelling of approved values and the complete food-period header', () => {
    const original: TemplateSheet = { name: 'QF_2_상품정보', columns: [
      column(42, '과세여부', ['과세', '면세', '영세']),
      column(44, '거래타입', ['제조사', '공식총판사', '공식대리점', '기타 도소매업자']),
      column(47, '유통기간 *식품의 경우 소비기간\n(일수기재)'),
      column(48, '취급주의 사유', ['해당사항없음', '유리']),
      column(70, '취급주의사항'),
    ] }
    const before = structuredClone(original)
    const result = applyRegistrationDefaults(row(), original)
    expect(result.fields).toEqual({
      과세여부: '과세', 거래타입: '기타 도소매업자',
      '유통기간 *식품의 경우 소비기간\n(일수기재)': '0', '취급주의 사유': '해당사항없음', 취급주의사항: '상세페이지 참고',
    })
    expect(result.defaultedFields).toEqual(result.fields)
    expect(original).toEqual(before)
    expect(applyRegistrationDefaults(result, original)).toBe(result)
  })

  it('recognizes spacing and legacy header variants but leaves expiry dates and unrelated automatic fields blank', () => {
    const selected = sheet('과세 여부', '거래 유형', '유통기간', '취급주의(사용)', '취급 시 주의사항', '취급시주의사항(설명)', '유통기한', '카테고리', '출시연도', '자동 인증번호')
    selected.columns.at(-1)!.autoGenerated = true
    const result = applyRegistrationDefaults(row(), selected)
    expect(result.fields).toEqual({ '과세 여부': '과세', '거래 유형': '기타도소매업자', 유통기간: '0', '취급주의(사용)': '해당없음', '취급 시 주의사항': '상세페이지 참고', '취급시주의사항(설명)': '상세페이지 참고' })
    const empty = row()
    expect(applyRegistrationDefaults(empty, sheet())).toBe(empty)
  })

  it('fills all approved certification-related headers while retaining exact official keys', () => {
    const labels = [
      '전기용품 및 생활용품, 어린이 (KC) 인증 마크 타입',
      '전기용품 및 생활용품, 어린이 (KC) 인증번호',
      '방송통신 기자재(EMC)인증번호', 'KC 인증정보', '인증 기관',
    ]
    const result = applyRegistrationDefaults(row(), sheet(...labels))
    expect(result.fields).toEqual(Object.fromEntries(labels.map(label => [label, '해당사항없음'])))
  })

  it('retains manual values, dropdown selections and deliberate clears over every fixed default', () => {
    const selected = sheet('과세여부', '거래타입', '유통기간', '취급주의 사유', '취급주의사항', 'KC 인증정보')
    const initial = applyRegistrationDefaults(row(), selected)
    for (const value of ['', '직접 확인한 값']) {
      const edited = { ...initial, fields: Object.fromEntries(selected.columns.map(column => [column.label, value])) }
      expect(applyRegistrationDefaults(edited, selected)).toBe(edited)
    }
    const manual = row({ fields: { 과세여부: '면세', 거래타입: '제조사', 유통기간: '365', '취급주의 사유': '유리', 취급주의사항: '파손주의', 'KC 인증정보': '확인한 인증번호' } })
    expect(applyRegistrationDefaults(manual, selected)).toBe(manual)
  })

  it('defaults the duplicate second color from the effective first manual color rather than the option color', () => {
    const selected: TemplateSheet = { name: 'QF_2_색상', columns: [column(7, '색상'), column(62, '색상')] }
    const initial = row()
    const firstKey = registrationFieldKey(initial, selected, selected.columns[0])
    const secondKey = registrationFieldKey(initial, selected, selected.columns[1])
    const result = applyRegistrationDefaults({ ...initial, fields: { [firstKey]: '직접 확인한 브라운' } }, selected)
    expect(result.fields).toEqual({ [firstKey]: '직접 확인한 브라운', [secondKey]: '직접 확인한 브라운' })
    expect(result.defaultedFields).toEqual({ [secondKey]: '직접 확인한 브라운' })
    expect(registrationFieldValue(result, selected, selected.columns[0])).toBe('직접 확인한 브라운')
    const changed = applyRegistrationDefaults({ ...result, fields: { ...result.fields, [firstKey]: '그레이' } }, selected)
    expect(changed.fields[secondKey]).toBe('그레이')
    for (const value of ['', '별도 확인한 색상']) {
      const edited = { ...result, fields: { ...result.fields, [firstKey]: '그레이', [secondKey]: value } }
      expect(applyRegistrationDefaults(edited, selected).fields[secondKey]).toBe(value)
    }
  })

  it('keeps explicit duplicate clears and handles the literal second-color header', () => {
    const duplicated = sheet('색상', '색상')
    const base = row({ fields: { 색상: '기존 공유 값' } })
    const firstKey = registrationFieldKey(base, duplicated, duplicated.columns[0])
    const secondKey = registrationFieldKey(base, duplicated, duplicated.columns[1])
    expect(applyRegistrationDefaults({ ...base, fields: { ...base.fields, [secondKey]: '' } }, duplicated).fields[secondKey]).toBe('')
    const clearedFirst = applyRegistrationDefaults(row({ fields: { [firstKey]: '' } }), duplicated)
    expect(clearedFirst.fields[firstKey]).toBe('')
    expect(clearedFirst.fields).not.toHaveProperty(secondKey)
    expect(applyRegistrationDefaults(row({ fields: { 색상: '네이비' } }), sheet('색상', '색상 2')).fields).toEqual({ 색상: '네이비', '색상 2': '네이비' })
  })

  it('uses only a known whole color option and preserves product dimensions separately from packaging', () => {
    const result = applyProductMasterDefaults(row({ productMaster: master }))
    expect(result.fields).toMatchObject({ 색상: '베이지', 사이즈: master.noticeSize, 치수: master.noticeSize, 크기: master.noticeSize, '한 개 단품 포장 사이즈': '270*140*430' })
    const selected = sheet('색상', '색상', '사이즈', '치수')
    expect(applyRegistrationDefaults(row({ productMaster: master }), selected).fields).toMatchObject({ 사이즈: master.noticeSize, 치수: master.noticeSize })
    for (const optionName of ['30B', '30B 블랙', '2개입', '특대형', '블랙/화이트']) {
      expect(applyRegistrationDefaults(row({ optionName }), sheet('색상', '색상')).fields).toEqual({})
    }
    expect(applyProductMasterDefaults(row({ optionName: ' Beige ' })).fields.색상).toBe('Beige')
    expect(applyProductMasterDefaults(row({ bundleComponents: [], productMaster: master })).fields).not.toHaveProperty('색상')
    expect(applyProductMasterDefaults(row({ bundleComponents: [], productMaster: master })).fields).not.toHaveProperty('사이즈')
  })

  it.each(['queued', 'running', 'login_required', 'succeeded'] as const)('never changes a %s submission or a manually registered record', status => {
    const selected = sheet('과세여부', '인증정보', '색상', '색상')
    const locked = row({ submission: { status, jobId: 'protected' } })
    expect(applyRegistrationDefaults(locked, selected)).toBe(locked)
    const completed = row({ stage: 'registered' })
    expect(applyRegistrationDefaults(completed, selected)).toBe(completed)
  })
})
