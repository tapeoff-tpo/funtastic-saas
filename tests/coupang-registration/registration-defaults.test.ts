import { describe, expect, it } from 'vitest'
import { applyRegistrationDefaults, createRegistrationRow, PACKAGING_SIZE_FIELD, PACKAGING_WEIGHT_FIELD, type RegistrationProductMaster, type RegistrationRow, type TemplateSheet } from '@/lib/coupang-registration/model'

const master: RegistrationProductMaster = {
  itemId: 'item-1', match: 'sku', noticeSize: '25*12*41cm', noticeWeight: '400g',
  noticeMaterial: '철제', noticeManufacturer: '검증된 제조공장', noticeCountry: '중국',
}
const sheet = (...labels: string[]): TemplateSheet => ({ name: '공식 양식', columns: labels.map((label, index) => ({ column: index + 1, label, requirement: '필수', guide: '' })) })
const base = (overrides: Partial<RegistrationRow> = {}): RegistrationRow => ({ ...createRegistrationRow(), stage: 'information', ...overrides })
const allHeaders = sheet('브랜드', '상품 바코드', '수입자', '제조국', '제조자(수입자)', '제조사', PACKAGING_SIZE_FIELD, PACKAGING_WEIGHT_FIELD, '재질', '박스 내 SKU 수량')

describe('agreed Coupang registration defaults', () => {
  it('combines safe Product Management values with the agreed defaults in the selected sheet', () => {
    const row = base({ productMaster: master })
    const result = applyRegistrationDefaults(row, allHeaders)
    expect(result.fields).toEqual({
      브랜드: '생활살림', '상품 바코드': '바코드 없음(쿠팡 바코드 생성 요청)', 수입자: '테이포프주식회사', 제조국: '중국',
      '제조자(수입자)': '검증된 제조공장 / 테이포프주식회사', 제조사: '검증된 제조공장',
      [PACKAGING_SIZE_FIELD]: '270*140*430', [PACKAGING_WEIGHT_FIELD]: '400', 재질: '철제', '박스 내 SKU 수량': '20',
    })
    expect(result.defaultedFields).toEqual(result.fields)
    expect(row.fields).toEqual({})
    expect(applyRegistrationDefaults(result, allHeaders)).toBe(result)
  })

  it('adds approved values only to selected editable headers without guessing a category or expiry date', () => {
    const row = base({ productMaster: master, fields: { 보존할값: '기존 데이터' } })
    const selected = sheet('브랜드', '카테고리', '인증정보', '과세여부', '거래유형', '유통기한', '제조국')
    selected.columns.at(-1)!.autoGenerated = true
    const result = applyRegistrationDefaults(row, selected)
    expect(result.fields).toEqual({ 보존할값: '기존 데이터', 브랜드: '생활살림', 인증정보: '해당사항없음', 과세여부: '과세', 거래유형: '기타도소매업자' })
    expect(result.defaultedFields).toEqual({ 브랜드: '생활살림', 인증정보: '해당사항없음', 과세여부: '과세', 거래유형: '기타도소매업자' })
    expect(applyRegistrationDefaults(row, sheet())).toBe(row)
  })

  it('uses the agreed country and box defaults without inventing a missing factory or measurements', () => {
    const result = applyRegistrationDefaults(base(), allHeaders)
    expect(result.fields).toMatchObject({ 제조국: '중국', '박스 내 SKU 수량': '20', '제조자(수입자)': '테이포프주식회사' })
    for (const header of ['제조사', PACKAGING_SIZE_FIELD, PACKAGING_WEIGHT_FIELD, '재질']) expect(result.fields).not.toHaveProperty(header)
    expect(applyRegistrationDefaults(base(), sheet('상품바코드')).fields).toEqual({ 상품바코드: '바코드 없음(쿠팡 바코드 생성 요청)' })
  })

  it('fills the confirmed import choice only when present and preserves an override or deliberate clear', () => {
    const selected = sheet('수입여부')
    const initial = applyRegistrationDefaults(base(), selected)
    expect(initial.fields).toEqual({ 수입여부: '수입상품' })
    expect(applyRegistrationDefaults({ ...initial, fields: { 수입여부: '' } }, selected).fields.수입여부).toBe('')
    const overridden = base({ fields: { 수입여부: '직접 선택한 값' } })
    expect(applyRegistrationDefaults(overridden, selected)).toBe(overridden)
    expect(applyRegistrationDefaults(base(), sheet())).not.toHaveProperty('fields.수입여부')
  })

  it('preserves every explicit user or imported value over both master data and agreed defaults', () => {
    const fields = {
      브랜드: '입력한 브랜드', '상품 바코드': '8801234567890', 수입자: '입력한 수입자', 제조국: '한국',
      '제조자(수입자)': '직접 확인한 표기', 제조사: '입력한 제조공장',
      [PACKAGING_SIZE_FIELD]: '900*900*900', [PACKAGING_WEIGHT_FIELD]: '900', 재질: '스테인리스', '박스 내 SKU 수량': '12',
    }
    const row = base({ productMaster: master, fields })
    expect(applyRegistrationDefaults(row, allHeaders)).toBe(row)
    expect(row.fields).toEqual(fields)
    expect(row.defaultedFields).toBeUndefined()
  })

  it('preserves deliberate clears using prior default tracking, including box quantity and packing dimensions', () => {
    const initial = applyRegistrationDefaults(base({ productMaster: master }), allHeaders)
    const cleared = { ...initial, fields: Object.fromEntries(Object.keys(initial.fields).map(label => [label, ''])) }
    const row = { ...cleared, productMaster: { ...master, noticeSize: '90*90*90cm', noticeCountry: '한국' } }
    expect(applyRegistrationDefaults(row, allHeaders)).toBe(row)
    expect(row.fields[PACKAGING_SIZE_FIELD]).toBe('')
    expect(row.fields['박스 내 SKU 수량']).toBe('')
  })

  it.each([
    ['400*400*199', '20'], ['400*400*200', '20'], ['400*400*201', '1'],
    ['40 × 40 × 20 cm', '20'], ['40x40x20.1cm', '1'],
    ['', '20'], ['미정', '20'], ['600*600', '20'], ['600*600*0', '20'],
    ['-1*600*600', '20'], ['100*100*100*2000', '20'],
  ])('uses 1 per box only when all effective dimensions are known and exceed 1000mm: %s', (size, quantity) => {
    const result = applyRegistrationDefaults(base({ fields: { [PACKAGING_SIZE_FIELD]: size } }), sheet('박스 내 SKU 수량'))
    expect(result.fields['박스 내 SKU 수량']).toBe(quantity)
    expect(result.fields[PACKAGING_SIZE_FIELD]).toBe(size)
  })

  it('uses the manual packed size instead of a larger master size and respects a cleared master default', () => {
    const row = base({ productMaster: { ...master, noticeSize: '90*90*90cm' }, fields: { [PACKAGING_SIZE_FIELD]: '100*100*100' } })
    expect(applyRegistrationDefaults(row, allHeaders).fields['박스 내 SKU 수량']).toBe('20')
    const cleared = { ...row, fields: { [PACKAGING_SIZE_FIELD]: '' }, defaultedFields: { [PACKAGING_SIZE_FIELD]: '920*920*920' } }
    const result = applyRegistrationDefaults(cleared, allHeaders)
    expect(result.fields[PACKAGING_SIZE_FIELD]).toBe('')
    expect(result.fields['박스 내 SKU 수량']).toBe('20')
  })

  it('includes packing clearance before the threshold and refreshes only unedited prior defaults', () => {
    const exact = applyRegistrationDefaults(base({ productMaster: { ...master, noticeSize: '29*29*36cm' } }), allHeaders)
    expect(exact.fields[PACKAGING_SIZE_FIELD]).toBe('310*310*380')
    expect(exact.fields['박스 내 SKU 수량']).toBe('20')
    const result = applyRegistrationDefaults({ ...exact, productMaster: { ...master, noticeSize: '29*29*36.1cm', noticeCountry: '한국' } }, allHeaders)
    expect(result.fields).toMatchObject({ [PACKAGING_SIZE_FIELD]: '310*310*381', '박스 내 SKU 수량': '1', 제조국: '한국' })
    expect(result.defaultedFields?.['박스 내 SKU 수량']).toBe('1')
  })

  it('keeps the factory separate while composing the combined field with the effective importer', () => {
    const row = base({ productMaster: master, fields: { 수입자: '직접 확인한 수입자', 제조사: '직접 확인한 공장' } })
    const result = applyRegistrationDefaults(row, sheet('제조사', '수입자', '제조자(수입자)'))
    expect(result.fields.제조사).toBe('직접 확인한 공장')
    expect(result.fields.수입자).toBe('직접 확인한 수입자')
    expect(result.fields['제조자(수입자)']).toBe('직접 확인한 공장 / 직접 확인한 수입자')
    expect(applyRegistrationDefaults(base({ fields: { 제조사: '직접 확인한 공장' } }), sheet('제조자(수입자)')).fields['제조자(수입자)']).toBe('직접 확인한 공장 / 테이포프주식회사')
  })

  it('does not reintroduce a deliberately cleared factory or importer into the combined field', () => {
    const initial = applyRegistrationDefaults(base({ productMaster: master }), allHeaders)
    const factoryCleared = applyRegistrationDefaults({ ...initial, fields: { ...initial.fields, 제조사: '' } }, allHeaders)
    expect(factoryCleared.fields.제조사).toBe('')
    expect(factoryCleared.fields['제조자(수입자)']).toBe('테이포프주식회사')
    const importerCleared = applyRegistrationDefaults({ ...initial, fields: { ...initial.fields, 수입자: '' } }, allHeaders)
    expect(importerCleared.fields.수입자).toBe('')
    expect(importerCleared.fields['제조자(수입자)']).toBe('검증된 제조공장')
  })

  it.each(['queued', 'running', 'login_required', 'succeeded'] as const)('never mutates a row with a %s submission', status => {
    const row = base({ productMaster: master, submission: { status, jobId: 'job-1' } })
    expect(applyRegistrationDefaults(row, allHeaders)).toBe(row)
    expect(row.fields).toEqual({})
  })

  it('never mutates a registered row, even a legacy row without receipt details', () => {
    const row = base({ stage: 'registered', productMaster: master })
    expect(applyRegistrationDefaults(row, allHeaders)).toBe(row)
  })
})
